class DriverTrip {
  final String from;
  final String to;
  final double fare;
  final String time;
  final int passengers;
  final double rating;
  final String date;

  const DriverTrip({
    required this.from,
    required this.to,
    required this.fare,
    required this.time,
    required this.passengers,
    required this.rating,
    required this.date,
  });
}